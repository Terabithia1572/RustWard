#!/usr/bin/env bash
# Write docs/DEPENDENCY-INVENTORY.md: every third-party crate compiled into the
# shipped Windows x64 artifacts (normal + build edges, all features) and every
# npm production dependency. Read-only except for the output file.
set -euo pipefail
cd "$(dirname "$0")/.."
out=docs/DEPENDENCY-INVENTORY.md
target=x86_64-pc-windows-msvc

crates() { # $1 = manifest
  cargo tree --manifest-path "$1" --workspace --locked --all-features --target "$target" \
    -e normal,build --prefix none -f '{p}|{l}' 2>/dev/null |
    grep -v '(\*)' | grep -v '/home\|path+' | grep -v '^rustward' | sed 's/ (proc-macro)//' |
    grep -v '^[[:space:]]*$' | sort -u | awk -F'|' '{ split($1,a," "); printf "| %s | %s | %s |\n", a[1], a[2], ($2==""?"(none declared)":$2) }'
}

{
  echo "# Dependency inventory"
  echo
  echo "Generated by \`scripts/dependency-inventory.sh\` on $(date -u +%Y-%m-%d) for target \`$target\`"
  echo "(normal + build dependencies, all features; dev-only crates excluded). Licence and"
  echo "advisory policy: \`deny.toml\` (\`cargo deny check\`). Regenerate after every lockfile change."
  echo
  echo "## Service, inventory CLI and libraries (\`Cargo.lock\`)"
  echo
  echo "| Crate | Version | Licence |"
  echo "|---|---|---|"
  crates Cargo.toml
  echo
  case "$(uname -s)" in
    MINGW*|MSYS*|CYGWIN*) ;;
    *)
      echo 'Generated on a non-Windows host: `cargo tree` evaluates the `cfg(windows)` build dependency'
      echo "against the host, so the service's Windows-only build dependency **embed-resource 3.0.12 (MIT)**"
      echo 'and its dependencies (vswhom, vswhom-sys, winreg, toml, …; all in `cargo deny list`) are'
      echo 'not listed above. Regenerate on the Windows build machine for the exact list.'
      echo ;;
  esac
  echo "## Desktop shell (\`apps/rustward-desktop/src-tauri/Cargo.lock\`)"
  echo
  echo "| Crate | Version | Licence |"
  echo "|---|---|---|"
  crates apps/rustward-desktop/src-tauri/Cargo.toml
  echo
  echo "## Frontend production dependencies (\`apps/rustward-desktop/package-lock.json\`)"
  echo
  echo "| Package | Version | Licence |"
  echo "|---|---|---|"
  ( cd apps/rustward-desktop && node -e '
      const lock = require("./package-lock.json");
      const rows = [];
      for (const [path, p] of Object.entries(lock.packages || {})) {
        if (!path || p.dev || p.devOptional) continue;
        const name = path.replace(/^.*node_modules\//, "");
        rows.push(`| ${name} | ${p.version} | ${p.license || "(none declared)"} |`);
      }
      console.log([...new Set(rows)].sort().join("\n"));
    ' )
} > "$out"
echo "wrote $out"
