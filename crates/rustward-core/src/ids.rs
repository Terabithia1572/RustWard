//! Parsing and encoding of Windows Plug and Play identifier strings.
//!
//! Two identifier families matter for USB storage:
//!
//! 1. USB device IDs, e.g. `USB\VID_0781&PID_5581&REV_0100`. The VID is
//!    assigned by the USB-IF to a *company*, but Windows exposes no
//!    VID-only hardware ID, so device-installation policy cannot match
//!    "all products of VID 0781" without listing every PID.
//! 2. Storage IDs generated from SCSI INQUIRY data by USBSTOR (bulk-only
//!    transport) and by the SCSI/Storport stack (UASP). Microsoft documents
//!    the USBSTOR format as `USBSTOR\t*v(8)p(16)r(4)` with additional
//!    hardware IDs including the *vendor-level* `USBSTOR\t*v(8)`, e.g.
//!    `USBSTOR\DiskSEAGATE_`. That vendor-level ID is the only brand-level
//!    identifier Windows exposes to device installation policy.
//!
//! The INQUIRY vendor field is an 8-byte ASCII string chosen by device
//! firmware. It is neither unique nor authenticated (see
//! `docs/BRAND-IDENTIFICATION.md`).

use serde::{Deserialize, Serialize};
use thiserror::Error;

/// Width of the SCSI INQUIRY vendor identification field.
pub const INQUIRY_VENDOR_LEN: usize = 8;
/// Width of the SCSI INQUIRY product identification field.
pub const INQUIRY_PRODUCT_LEN: usize = 16;
/// Width of the SCSI INQUIRY product revision field.
pub const INQUIRY_REVISION_LEN: usize = 4;

/// SCSI device-type strings used in USBSTOR/SCSI hardware IDs
/// (Microsoft "Identifiers Generated by USBSTOR" type table).
pub const SCSI_DEVICE_TYPES: &[&str] = &[
    "Disk",
    "SFloppy",
    "Sequential",
    "Worm",
    "CdRom",
    "Optical",
    "Changer",
    "Other",
];

/// Errors from identifier encoding.
#[derive(Debug, Clone, PartialEq, Eq, Error)]
pub enum IdError {
    /// INQUIRY strings are ASCII; non-ASCII text (e.g. "TÜBİTAK") can never
    /// appear in an INQUIRY-derived hardware ID.
    #[error(
        "value {0:?} contains non-printable or non-ASCII characters; SCSI INQUIRY fields are ASCII"
    )]
    NotPrintableAscii(String),
    /// The value is longer than the INQUIRY field.
    #[error("value {value:?} is longer than the {width}-character INQUIRY field")]
    TooLong {
        /// Offending value.
        value: String,
        /// Field width.
        width: usize,
    },
    /// Empty or whitespace-only value.
    #[error("value is empty")]
    Empty,
}

/// Which identifier namespace produced a storage hardware ID.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "SCREAMING_SNAKE_CASE")]
pub enum StorageIdNamespace {
    /// `USBSTOR\...` — USB Mass Storage Bulk-Only Transport via usbstor.sys.
    /// Format documented by Microsoft.
    Usbstor,
    /// `SCSI\...` — Storport-enumerated disks. Used by UASP (uaspstor.sys)
    /// **and by internal SATA/NVMe disks**. The exact vendor-level padding
    /// for this namespace must be confirmed on hardware (Phase 1 inventory).
    Scsi,
}

impl StorageIdNamespace {
    /// Hardware-ID prefix including the trailing backslash.
    #[must_use]
    pub const fn prefix(self) -> &'static str {
        match self {
            Self::Usbstor => "USBSTOR\\",
            Self::Scsi => "SCSI\\",
        }
    }

    /// All namespaces.
    pub const ALL: [Self; 2] = [Self::Usbstor, Self::Scsi];

    /// Whether the vendor-level ID format for this namespace is documented
    /// by Microsoft with an example (USBSTOR) or still needs hardware
    /// confirmation (SCSI).
    #[must_use]
    pub const fn vendor_level_format_documented(self) -> bool {
        matches!(self, Self::Usbstor)
    }
}

/// A USB vendor/product pair parsed from a USB device or instance ID.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub struct UsbVidPid {
    /// USB-IF assigned vendor ID.
    pub vid: u16,
    /// Vendor-assigned product ID.
    pub pid: u16,
}

impl UsbVidPid {
    /// `VID` formatted the way Windows prints it (4 upper-case hex digits).
    #[must_use]
    pub fn vid_hex(&self) -> String {
        format!("{:04X}", self.vid)
    }
}

/// Parse `VID_xxxx&PID_yyyy` from a USB hardware ID or instance ID such as
/// `USB\VID_0781&PID_5581&REV_0100` or `USB\VID_1A2B&PID_0001&MI_01\6&1&0&1`.
/// Returns `None` for hubs (`USB\ROOT_HUB30`) and anything malformed.
#[must_use]
pub fn parse_usb_vid_pid(id: &str) -> Option<UsbVidPid> {
    let upper = id.to_ascii_uppercase();
    let rest = upper.strip_prefix("USB\\VID_")?;
    let vid = parse_hex4(rest.get(0..4)?)?;
    let rest = rest.get(4..)?.strip_prefix("&PID_")?;
    let pid = parse_hex4(rest.get(0..4)?)?;
    Some(UsbVidPid { vid, pid })
}

fn parse_hex4(s: &str) -> Option<u16> {
    if s.len() == 4 && s.bytes().all(|b| b.is_ascii_hexdigit()) {
        u16::from_str_radix(s, 16).ok()
    } else {
        None
    }
}

/// Parse a 4-hex-digit VID string such as `"0781"`.
#[must_use]
pub fn parse_vid(s: &str) -> Option<u16> {
    parse_hex4(s.trim())
}

/// Encode an INQUIRY string the way it appears inside a USBSTOR hardware ID:
/// right-padded with spaces to `width`, then spaces (and commas) replaced by
/// `_`.
///
/// The space→`_` rule is documented by Microsoft's USBSTOR example
/// (`USBSTOR\DiskSEAGATE_`). Treating `,` the same way is an engineering
/// assumption (commas are not allowed in device IDs) pending hardware
/// confirmation. Non-ASCII input is rejected rather than guessed.
pub fn encode_inquiry_field(value: &str, width: usize) -> Result<String, IdError> {
    if value.trim().is_empty() {
        return Err(IdError::Empty);
    }
    if !value.chars().all(|c| c.is_ascii() && !c.is_ascii_control()) {
        return Err(IdError::NotPrintableAscii(value.to_owned()));
    }
    if value.len() > width {
        return Err(IdError::TooLong {
            value: value.to_owned(),
            width,
        });
    }
    let padded = format!("{value:<width$}");
    Ok(padded
        .chars()
        .map(|c| if c == ' ' || c == ',' { '_' } else { c })
        .collect())
}

/// The vendor-level hardware ID Windows generates for an INQUIRY vendor in a
/// namespace, e.g. (`Usbstor`, `"Disk"`, `"SanDisk"`) → `USBSTOR\DiskSanDisk_`.
pub fn vendor_level_hardware_id(
    namespace: StorageIdNamespace,
    device_type: &str,
    inquiry_vendor: &str,
) -> Result<String, IdError> {
    let field = encode_inquiry_field(inquiry_vendor, INQUIRY_VENDOR_LEN)?;
    Ok(format!("{}{}{}", namespace.prefix(), device_type, field))
}

/// INQUIRY-derived identity recovered from a storage devnode's hardware IDs.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct InquiryIdentity {
    /// Namespace (`USBSTOR` or `SCSI`).
    pub namespace: StorageIdNamespace,
    /// SCSI device-type string, e.g. `Disk`, `CdRom`.
    pub device_type: String,
    /// The vendor-level hardware ID exactly as Windows reported it, e.g.
    /// `USBSTOR\DiskSanDisk_`. This is the string a device-installation
    /// allow rule must equal.
    pub vendor_level_id: String,
    /// The vendor field as encoded in the ID (normally 8 characters,
    /// `_`-padded).
    pub vendor_field: String,
    /// Product field, when the full hardware ID was present.
    pub product_field: Option<String>,
    /// Revision field, when the full hardware ID was present.
    pub revision_field: Option<String>,
}

impl InquiryIdentity {
    /// Human-readable vendor (padding removed). Lossy: a literal `_` in
    /// firmware data cannot be distinguished from padding.
    #[must_use]
    pub fn vendor_display(&self) -> String {
        self.vendor_field.trim_end_matches('_').replace('_', " ")
    }

    /// Human-readable product (padding removed, lossy).
    #[must_use]
    pub fn product_display(&self) -> Option<String> {
        self.product_field
            .as_ref()
            .map(|p| p.trim_end_matches('_').replace('_', " "))
    }
}

/// Split `<NS>\<Type><remainder>` into (namespace, canonical type, remainder).
fn split_storage_id(id: &str) -> Option<(StorageIdNamespace, &'static str, &str)> {
    for ns in StorageIdNamespace::ALL {
        let prefix = ns.prefix();
        let Some(head) = id.get(..prefix.len()) else {
            continue;
        };
        if !head.eq_ignore_ascii_case(prefix) {
            continue;
        }
        let after = &id[prefix.len()..];
        for ty in SCSI_DEVICE_TYPES {
            if let Some(h) = after.get(..ty.len())
                && h.eq_ignore_ascii_case(ty)
            {
                return Some((ns, ty, &after[ty.len()..]));
            }
        }
    }
    None
}

/// Recover the INQUIRY identity from a storage devnode's hardware IDs.
///
/// The vendor-level ID is taken to be the shortest `<NS>\<Type><vendor>` ID
/// whose remainder is 1..=8 ASCII characters and is a prefix of every
/// longer ID's remainder in the same namespace/type. Returns `None` if no
/// such ID exists — the device then has no enforceable brand identity.
#[must_use]
pub fn parse_inquiry_identity(hardware_ids: &[String]) -> Option<InquiryIdentity> {
    let parsed: Vec<_> = hardware_ids
        .iter()
        .filter_map(|id| split_storage_id(id).map(|(ns, ty, rest)| (id, ns, ty, rest)))
        .filter(|(_, _, _, rest)| rest.is_ascii() && !rest.is_empty())
        .collect();

    let (vendor_id, ns, ty, vendor_rest) = parsed
        .iter()
        .filter(|(_, _, _, rest)| rest.len() <= INQUIRY_VENDOR_LEN)
        .min_by_key(|(_, _, _, rest)| rest.len())?;

    let longer: Vec<_> = parsed
        .iter()
        .filter(|(_, n, t, rest)| n == ns && t == ty && rest.len() > vendor_rest.len())
        .collect();
    let consistent = longer.iter().all(|(_, _, _, rest)| {
        rest.get(..vendor_rest.len())
            .is_some_and(|p| p.eq_ignore_ascii_case(vendor_rest))
    });
    if !consistent {
        return None;
    }

    let full_width = INQUIRY_VENDOR_LEN + INQUIRY_PRODUCT_LEN;
    let product_field = longer
        .iter()
        .find(|(_, _, _, rest)| rest.len() >= full_width)
        .and_then(|(_, _, _, rest)| rest.get(INQUIRY_VENDOR_LEN..full_width))
        .map(str::to_owned);
    let revision_field = longer
        .iter()
        .find(|(_, _, _, rest)| rest.len() > full_width)
        .and_then(|(_, _, _, rest)| rest.get(full_width..))
        .map(str::to_owned);

    Some(InquiryIdentity {
        namespace: *ns,
        device_type: (*ty).to_owned(),
        vendor_level_id: (*vendor_id).clone(),
        vendor_field: (*vendor_rest).to_owned(),
        product_field,
        revision_field,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    fn ids(v: &[&str]) -> Vec<String> {
        v.iter().map(|s| (*s).to_owned()).collect()
    }

    #[test]
    fn parses_usb_vid_pid_variants() {
        let a = parse_usb_vid_pid("USB\\VID_0781&PID_5581&REV_0100").unwrap();
        assert_eq!((a.vid, a.pid), (0x0781, 0x5581));
        let b = parse_usb_vid_pid("usb\\vid_1a2b&pid_0001&mi_01\\6&1&0&1").unwrap();
        assert_eq!((b.vid, b.pid), (0x1A2B, 0x0001));
        assert_eq!(b.vid_hex(), "1A2B");
        assert!(parse_usb_vid_pid("USB\\ROOT_HUB30\\4&1&0&0").is_none());
        assert!(parse_usb_vid_pid("USB\\VID_07G1&PID_5581").is_none());
        assert!(parse_usb_vid_pid("USBSTOR\\DiskSanDisk_").is_none());
        assert!(parse_usb_vid_pid("USB\\VID_078").is_none());
    }

    #[test]
    fn encodes_microsoft_documented_example() {
        // Microsoft example: vendor "SEAGATE" → USBSTOR\DiskSEAGATE_
        assert_eq!(
            vendor_level_hardware_id(StorageIdNamespace::Usbstor, "Disk", "SEAGATE").unwrap(),
            "USBSTOR\\DiskSEAGATE_"
        );
        assert_eq!(encode_inquiry_field("Kingston", 8).unwrap(), "Kingston");
        assert_eq!(encode_inquiry_field("WD", 8).unwrap(), "WD______");
        assert_eq!(encode_inquiry_field("A B", 8).unwrap(), "A_B_____");
    }

    #[test]
    fn rejects_values_that_cannot_appear_in_inquiry_data() {
        assert!(matches!(
            encode_inquiry_field("TÜBİTAK", 8),
            Err(IdError::NotPrintableAscii(_))
        ));
        assert!(matches!(
            encode_inquiry_field("TOOLONGVENDOR", 8),
            Err(IdError::TooLong { .. })
        ));
        assert_eq!(encode_inquiry_field("   ", 8), Err(IdError::Empty));
        assert!(encode_inquiry_field("A\tB", 8).is_err());
    }

    #[test]
    fn recovers_identity_from_documented_usbstor_example() {
        let hw = ids(&[
            "USBSTOR\\DiskSEAGATE_ST39102LW_______0004",
            "USBSTOR\\DiskSEAGATE_ST39102LW_______",
            "USBSTOR\\DiskSEAGATE_",
            "USBSTOR\\SEAGATE_ST39102LW_______0",
            "SEAGATE_ST39102LW_______0",
            "USBSTOR\\GenDisk",
            "GenDisk",
        ]);
        let id = parse_inquiry_identity(&hw).unwrap();
        assert_eq!(id.namespace, StorageIdNamespace::Usbstor);
        assert_eq!(id.device_type, "Disk");
        assert_eq!(id.vendor_level_id, "USBSTOR\\DiskSEAGATE_");
        assert_eq!(id.vendor_field, "SEAGATE_");
        assert_eq!(id.vendor_display(), "SEAGATE");
        assert_eq!(id.product_field.as_deref(), Some("ST39102LW_______"));
        assert_eq!(id.revision_field.as_deref(), Some("0004"));
        assert_eq!(id.product_display().as_deref(), Some("ST39102LW"));
    }

    #[test]
    fn generic_ids_are_not_mistaken_for_vendor_ids() {
        // "USBSTOR\GenDisk" must not parse as type "GenDisk"/vendor.
        assert!(parse_inquiry_identity(&ids(&["USBSTOR\\GenDisk", "GenDisk"])).is_none());
    }

    #[test]
    fn missing_vendor_level_id_yields_no_identity() {
        let hw = ids(&["USBSTOR\\DiskSanDisk_Ultra___________1.00"]);
        assert!(parse_inquiry_identity(&hw).is_none());
    }

    #[test]
    fn inconsistent_vendor_ids_fail_closed() {
        let hw = ids(&[
            "USBSTOR\\DiskKingstonDataTraveler_3.0PMAP",
            "USBSTOR\\DiskSanDisk_",
        ]);
        assert!(parse_inquiry_identity(&hw).is_none());
    }

    #[test]
    fn parses_scsi_namespace_and_cdrom_type() {
        let hw = ids(&[
            "SCSI\\DiskSeagate_Expansion_HDD___0605",
            "SCSI\\DiskSeagate_Expansion_HDD___",
            "SCSI\\DiskSeagate_",
        ]);
        let id = parse_inquiry_identity(&hw).unwrap();
        assert_eq!(id.namespace, StorageIdNamespace::Scsi);
        assert_eq!(id.vendor_display(), "Seagate");

        let cd = parse_inquiry_identity(&ids(&[
            "USBSTOR\\CdRomHL-DT-ST",
            "USBSTOR\\CdRomHL-DT-STDVDRAM_GP57EB40_PR10",
        ]))
        .unwrap();
        assert_eq!(cd.device_type, "CdRom");
        assert_eq!(cd.vendor_field, "HL-DT-ST");
    }
}
